import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';

const root=process.cwd();
const dom=readFileSync(join(root,'web-adapter/chatgpt-dom.js'),'utf8');
const content=readFileSync(join(root,'web-adapter/chrome-extension-current/content.js'),'utf8');
const worker=readFileSync(join(root,'web-adapter/chrome-extension-current/service-worker.js'),'utf8');

assert.match(dom,/function selectedPayload/,'current GPT selection binding resolves an execution payload');
assert.match(dom,/function mountComposerAiccAction/,'current canonical composer action mounts the executable surface');
assert.match(dom,/selectedPayload,.*mountComposerAiccAction/,'current GPT execution-surface primitives are exported by the canonical DOM adapter');
assert.match(content,/const canonicalImportAndRun = \(text, originContext\) => sendTask\(text, originContext, 'Composer', 'IMPORT_AND_RUN'/,'GPT execution surfaces use the canonical import-and-run route');
assert.match(dom,/blockId/);
assert.match(dom,/function originContext/,'execution payloads carry canonical origin context');
assert.match(content,/function resolveTaskSource\(\) \{ return window\.AICCChatGPTDom\.selectedPayload/,'current task selection uses the canonical selected-payload resolver');
const autoSubmit=dom.match(/async function submitChatGPTComposerOnce[\s\S]*?(?=\n  function exactNormalizedText)/)?.[0]??'';
assert.equal((dom.match(/\.click\(\)/g)??[]).length,1,'only the canonical verified ChatGPT submit primitive may click a native control');
assert.equal((autoSubmit.match(/sendButton\.click\(\)/g)??[]).length,1,'the primitive has one native ChatGPT Send interaction');
assert.match(content,/canonicalImportAndRun/);
assert.match(content,/IMPORT_AND_RUN/);
assert.match(dom,/AICC · 本地提交中/);
assert.match(dom,/AICC · 已提交/);
assert.match(dom,/data-aicc-action-error/);
assert.match(dom,/error\?\.code/);
assert.match(dom,/error\?\.reason/);
assert.match(worker,/function importAndRun/);
assert.match(worker,/async function sendInstruction[\s\S]*?request\('\/api\/gpt-bridge\/inbox'/,'canonical inbound action creates an Inbox receipt through the canonical submitter');
assert.match(worker,/function importAndRun\(message\) \{\s+return sendInstruction\(message\);/,'IMPORT_AND_RUN uses the canonical Inbox submission path');
const chatContentSurfaces=['assistant prose','user message','inline code','code block','Writing Block','editable Writing Block','nested content'];
assert.doesNotMatch(dom,/function mountAssistantAiccActions/,'chat-content assistant mount is removed');
assert.match(dom,/function removeChatContentFloatingButtons/,'existing chat-content buttons can be cleaned');
for (const surface of chatContentSurfaces) assert.doesNotMatch(dom,/function mountAssistantAiccActions/,`${surface} has zero AICC buttons`);
assert.match(dom,/function mountComposerAiccAction/,'Composer floating AICC button remains supported');
assert.match(content,/removeChatContentFloatingButtons\(document\)/,'chat-content cleanup is wired');
assert.match(content,/mountComposerAiccAction\(document/,'Composer maintenance is wired');
assert.doesNotMatch(content,/mountAssistantAiccActions/,'content script never reinjects chat-content buttons');
assert.match(content,/data-aicc-action-key="codex-execute"/,'right Bridge panel remains present');
assert.match(content,/data-aicc-codex-profile-trigger/,'model/reasoning selector remains present');
assert.equal(content.includes('button[type="submit"]'),false,'Assistant action never submits ChatGPT composer');
assert.equal(content.includes('KeyboardEvent'),false,'Bridge does not simulate keyboard shortcuts');
console.log('M4.1 Phase 2 GPT to AICC matrix passed');
