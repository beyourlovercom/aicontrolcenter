import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {applyHealthObservation} from './localServiceRecovery.ts';

const root=new URL('../../',import.meta.url);
const supervisor=readFileSync(new URL('scripts/aicc-local-service-supervisor.sh',root),'utf8');
assert.match(supervisor,/KeepAlive.*true|<key>KeepAlive<\/key>[\s\S]*?<true\/>/);
assert.match(supervisor,/is_transient_health_failure/);
const healthBranch=supervisor.slice(supervisor.indexOf('record_health_failure "$HEALTH_REASON" "$HEALTH_DETAIL"'),supervisor.indexOf('\n      else\n        MANAGED_PID=""',supervisor.indexOf('record_health_failure "$HEALTH_REASON" "$HEALTH_DETAIL"')));
assert.match(healthBranch,/\[ "\$CONSECUTIVE_FAILURES" -ge "\$HEALTH_FAILURE_THRESHOLD" \]/);
assert.match(healthBranch,/recover_unhealthy_managed_service "\$PORT_PID"/);
const transientBranch=healthBranch.slice(healthBranch.indexOf('elif is_transient_health_failure'),healthBranch.indexOf('\n        fi',healthBranch.indexOf('elif is_transient_health_failure')));
assert.doesNotMatch(transientBranch,/terminate_canonical_pid|start_official_service/);
assert.doesNotMatch(supervisor,/CONSECUTIVE_FAILURES=0\n        transition "HEALTHY"\n        echo "HEALTH_PROBE_SLOW/);
assert.match(supervisor,/start_after_true_process_death/);
assert.match(supervisor,/verified canonical Vite PID is no longer alive/);
assert.match(supervisor,/record_health_failure "\$LAST_HEALTH_FAILURE" "\$LAST_HEALTH_DETAIL"/);
assert.match(supervisor,/MANAGED_PID=""[\s\S]*?start_official_service/);
assert.match(supervisor,/recover_unhealthy_managed_service "\$MANAGED_PID"/);
assert.match(supervisor,/if \[ "\$SERVICE_STATE" = "RECOVERY_FAILED" \]; then/);
assert.doesNotMatch(supervisor,/LOCAL_SERVICE_PROCESS_DEATH_DETECTED/);
assert.match(supervisor,/LOCAL_SERVICE_OWNER_RESTART_REQUESTED/);
assert.doesNotMatch(supervisor,/restart\)[\s\S]*?launchctl kickstart/);
const state={state:'PROCESS_ALIVE_HEALTHY' as const,managedPid:101,consecutiveFailures:0,recoveryEpoch:0,recoveryAttempts:0};
const timeout=applyHealthObservation(state,{processAlive:true,healthOk:false,reason:'ETIMEDOUT',managedPidOwned:true});
const timeoutTwice=applyHealthObservation(timeout.state,{processAlive:true,healthOk:false,reason:'ETIMEDOUT',managedPidOwned:true});
assert.equal(timeout.action,'RETRY_HEALTH');
assert.equal(timeoutTwice.action,'TERMINATE_AND_RESTART');
assert.equal(timeoutTwice.state.managedPid,101);
assert.equal(timeoutTwice.state.recoveryAttempts,1);
assert.equal(timeoutTwice.state.state,'SERVICE_UNHEALTHY');
assert.equal(applyHealthObservation(timeoutTwice.state,{processAlive:true,healthOk:true}).state.state,'HEALTHY');
const dead=applyHealthObservation(state,{processAlive:false,healthOk:false,reason:'PROCESS_EXITED'});
assert.equal(dead.action,'START_SERVICE');
assert.equal(dead.state.state,'RESTARTING');
console.log('single local service lifecycle authority tests passed');
