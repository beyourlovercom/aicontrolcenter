import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {isRetryableRuntimeFailure} from './context/actionEligibility.ts';
import {INBOX_STATES,OUTBOX_STATES} from './bridgeCore.ts';

const root=process.cwd();
const bridge=readFileSync(join(root,'src/lib/bridgeCore.ts'),'utf8');
const app=readFileSync(join(root,'src/App.svelte'),'utf8');
const ownerActions=readFileSync(join(root,'src/components/entity/OwnerActionZone.svelte'),'utf8');
assert.equal(isRetryableRuntimeFailure({phase:'FAILED',failure:'PROVIDER_UNAVAILABLE'}),true);
assert.equal(isRetryableRuntimeFailure({phase:'FAILED',failure:'PROCESS_LAUNCH_FAILED'}),true);
assert.equal(isRetryableRuntimeFailure({phase:'STOPPED',failure:'PROCESS_LAUNCH_FAILED'}),false);
assert.equal(isRetryableRuntimeFailure({phase:'RECOVERY_REQUIRED',failure:'RUNTIME_CREATION_FAILED'}),true);
assert.equal(isRetryableRuntimeFailure({phase:'COMPLETED',failure:'PROVIDER_UNAVAILABLE'}),false,'a successful terminal run is not a retry projection');
assert.equal(isRetryableRuntimeFailure({phase:'RUNNING',failure:'PROVIDER_UNAVAILABLE'}),false);
assert.equal(INBOX_STATES.includes('CONSUMED'),true);
assert.equal(OUTBOX_STATES.includes('READY'),true);
assert.match(bridge,/function reconcilePersistedExecutions\(\)/);
assert.match(bridge,/export function readOutbox\(\)\{reconcilePersistedExecutions\(\);/);
assert.match(bridge,/x\.executionId===item\.executionId&&x\.runId===item\.runId/);
assert.match(bridge,/executionId:item\.executionId,runId:item\.runId/);
assert.match(app,/inboxResult\.status==='fulfilled'[\s\S]*bridgeInbox=scopeBridgeRecords\(inboxResult\.value\.items,activeRoadmapProject\)/,'live Runtime polling refreshes project-scoped downstream Inbox projection independently');
assert.match(app,/outboxResult\.status==='fulfilled'[\s\S]*bridgeOutbox=scopeBridgeRecords\(outboxResult\.value\.items,activeRoadmapProject\)/,'live Runtime polling refreshes project-scoped downstream Outbox projection independently');
assert.match(app,/bindLaunchedExecution\(result\.item\)/,'Bridge launch starts live Runtime projection through the shared launch binding');
assert.match(app,/runtimePollInFlight=false/,'live Runtime polling has overlap protection');
assert.match(app,/Promise\.allSettled\(\[query\?request\(`\/api\/codex\/runtime\$\{query\}`\):Promise\.resolve/,'live polling reads project-scoped canonical Runtime and downstream state together without cross-source failure coupling');
assert.match(ownerActions,/运行已完成，正在生成运行报告/,'report-pending is not projected as failure');
console.log('terminal downstream projection tests passed');
