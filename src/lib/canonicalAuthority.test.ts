import assert from 'node:assert/strict';
import {canonicalExecutionDecision} from './fastExecution.ts';

const repo={repository:process.cwd(),branch:'feature/x',head:'sha',localMain:'main',remoteMain:'main',worktree:'CLEAN',lastCommit:'sha'} as const;
const auth={workPackageId:'WP-1',branch:'feature/x',repositoryRoot:repo.repository,authoritySha:'main'};
const decide=(options:Parameters<typeof canonicalExecutionDecision>[5]={})=>canonicalExecutionDecision(repo,'WP-1',['src/allowed.ts'],[],[],options);
assert.equal(decide().decision,'CONTINUE');
assert.equal(decide().canContinue,true);
assert.equal(decide().severity,'AUTO_REMEDIATE');
assert.equal(decide({requireAuthorization:true,authorization:auth}).decision,'CONTINUE');
assert.equal(decide({requireAuthorization:true,authorization:undefined}).decision,'HARD_BLOCK');
assert.equal(decide({requireAuthorization:true,authorization:undefined}).reasonCode,'OWNER_AUTHORIZATION_REQUIRED');
assert.equal(decide({requireAuthorization:true,authorization:{...auth,workPackageId:'WP-2'}}).decision,'HARD_BLOCK');
assert.equal(decide({requireAuthorization:true,authorization:{...auth,branch:'main'}}).decision,'HARD_BLOCK');
assert.equal(decide({requireAuthorization:true,authorization:{...auth,authoritySha:'other'}}).decision,'HARD_BLOCK');
assert.equal(canonicalExecutionDecision({...repo,branch:'main'},'WP-1',[],[],[]).reasonCode,'FEATURE_BRANCH_REQUIRED');
assert.equal(canonicalExecutionDecision({...repo,repository:'unavailable'},'WP-1',[],[],[]).reasonCode,'REPOSITORY_UNAVAILABLE');
assert.equal(canonicalExecutionDecision({...repo,branch:'unavailable'},'WP-1',[],[],[]).reasonCode,'DETACHED_HEAD');
const dirtyRepo={...repo,worktree:'DIRTY' as const};
assert.equal(canonicalExecutionDecision(dirtyRepo,'WP-1',['src/allowed.ts'],['src/allowed.ts']).provenance,'KNOWN_IN_SCOPE_DIRTY');
assert.equal(canonicalExecutionDecision(dirtyRepo,'WP-1',['src/allowed.ts'],['notes'],['notes']).severity,'WARN');
assert.equal(canonicalExecutionDecision(dirtyRepo,'WP-1',['src/allowed.ts'],['unknown']).decision,'HARD_BLOCK');
assert.equal(canonicalExecutionDecision(dirtyRepo,'WP-1',['src/allowed.ts'],['unknown']).canContinue,false);
assert.equal(canonicalExecutionDecision(repo,'WP-1',[],[],[],{humanUatHardStop:true}).reasonCode,'HUMAN_UAT_HARD_STOP');
assert.equal(canonicalExecutionDecision(repo,'WP-1',[],[],[],{humanUatHardStop:true}).decision,'HARD_BLOCK');
assert.equal(decide().files.length,0);
assert.equal(typeof decide().reasonMessage,'string');
assert.equal(decide().lease,null);
assert.equal(decide().provenance,'CLEAN');
assert.ok(['CONTINUE','CONTINUE_WITH_WARNINGS','OWNER_DECISION_REQUIRED','HARD_BLOCK'].includes(decide().decision));
assert.equal(decide().nextAction,undefined);
console.log('canonical authority convergence tests passed');
