import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import vm from 'node:vm';

const script=readFileSync(join(process.cwd(),'web-adapter/chatgpt-dom.js'),'utf8');
const context={};vm.runInNewContext(script,context);
const dom=(context as {AICCChatGPTDom:{selectedPayload:(document:unknown,selection:unknown)=>{text:string}|null;actionSurfaces:(message:unknown)=>unknown[];actionPayload:(surface:unknown)=>string;originContext:(document:unknown,message:unknown)=>{conversationUrl?:string}}}).AICCChatGPTDom;
const ordinary='检查当前仓库，不修改任何文件。';
const protocol='AICC_EXECUTION_V1\nINSTRUCTION_BEGIN\n任意原始内容\nINSTRUCTION_END';
const ordinaryCode={innerText:ordinary};
const protocolCode={innerText:protocol};
assert.equal(dom.actionSurfaces({querySelectorAll:()=>[]}).length,0,'no structural source means no mount target');
assert.equal(dom.actionSurfaces({querySelectorAll:(selector:string)=>selector==='pre'?[ordinaryCode]:[]}).length,1,'generic code is a structural action source');
assert.equal(dom.actionPayload(ordinaryCode),ordinary,'ordinary text is passed without classification');
assert.equal(dom.actionPayload(protocolCode),protocol,'protocol-shaped text is not specially parsed');
const selectedNode={nodeType:1};
const selectedSurface={contains:(node:unknown)=>node===selectedNode,innerText:ordinary};
const selectedMessage={querySelectorAll:(selector:string)=>selector==='pre'?[selectedSurface]:[]};
const selected=dom.selectedPayload({querySelectorAll:(selector:string)=>selector.includes('assistant')?[selectedMessage]:[]},{toString:()=>ordinary,anchorNode:selectedNode,focusNode:selectedNode});
assert.equal(selected?.text,ordinary,'explicit selection is passed as-is');
assert.equal(dom.originContext({location:{href:'https://chatgpt.com/c/example'}},null).conversationUrl,'https://chatgpt.com/c/example');
console.log('direct Assistant structural capture matrix passed');
