import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import vm from 'node:vm';

const root=process.cwd();
const registrySource=readFileSync(join(root,'web-adapter/chrome-extension-current/bridge-action-registry.js'),'utf8');
const contentSource=readFileSync(join(root,'web-adapter/chrome-extension-current/content.js'),'utf8');
const workerSource=readFileSync(join(root,'web-adapter/chrome-extension-current/service-worker.js'),'utf8');
const viteSource=readFileSync(join(root,'vite.config.ts'),'utf8');
const context:any={window:{}};
vm.runInNewContext(registrySource,context);
const api=context.window.AICCBridgeActionRegistry;
const handlers:any=Object.fromEntries(['us-claude','clipboard-codex-execute','codex-execute','codex-result','aicc-send','next-step'].map(key=>[key,()=>undefined]));
const registry=api.createBridgeActionRegistry({handlers,capabilityResolver:()=>({enabled:true,disabledReason:''})});
const actions=Object.values(registry) as any[];

assert.equal(actions[0].actionKey,'us-claude');
assert.equal(actions[0].displayOrdinal,0);
assert.equal(actions[0].label,'US-Claude');
assert.deepEqual(actions.map(action=>action.displayOrdinal),[0,1,2,3,4,5]);
assert.deepEqual(actions.slice(0,2).map(action=>action.actionKey),['us-claude','clipboard-codex-execute']);
assert.match(contentSource,/executeUsClaude/);
assert.match(contentSource,/readInboundClipboard\(\)/);
assert.match(contentSource,/executionProvider: 'REMOTE_CLAUDE'/);
assert.match(contentSource,/runnerId: 'US-WAREHOUSE-01'/);
assert.match(contentSource,/copyAndInsertResult\(result\.text, result\.metadata\)/);
assert.doesNotMatch(contentSource.slice(contentSource.indexOf('async function executeUsClaude'),contentSource.indexOf('async function executeNextStep')),/submitChatGPTComposerOnce/);
assert.doesNotMatch(contentSource,/100\.94\.52\.109/);
assert.match(workerSource,/executionProvider: message\.executionProvider/);
assert.match(workerSource,/runnerId: message\.runnerId/);
assert.match(viteSource,/executionProvider:payload\.executionProvider/);
assert.match(viteSource,/runnerId:payload\.runnerId/);
assert.match(contentSource,/REMOTE_CLAUDE_STATUS/);
assert.match(workerSource,/remoteClaudeStatus/);
assert.match(viteSource,/api\/gpt-bridge\/remote-claude-status/);
assert.match(contentSource,/usClaudeAvailable && !usClaudeInFlight/);
assert.doesNotMatch(workerSource,/100\.94\.52\.109/);
assert.equal(contentSource.match(/stack\.addEventListener\('click'/g)?.length,1);
console.log('US-Claude Bridge button contract passed');
