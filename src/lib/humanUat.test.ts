import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {canPassHumanUat,resolveHumanUatStatus} from './humanUat.ts';
const workspace=readFileSync(new URL('../components/entity/HumanUatWorkspace.svelte',import.meta.url),'utf8');
const pass=[{id:'1',title:'a',description:'a',state:'PASS' as const},{id:'2',title:'b',description:'b',state:'N_A' as const}];
assert.equal(canPassHumanUat(pass),true);assert.equal(resolveHumanUatStatus(null,pass),'IN_PROGRESS');
assert.equal(canPassHumanUat([{...pass[0],state:'PENDING'}]),false);assert.equal(canPassHumanUat([{...pass[0],state:'FAIL'}]),false);
assert.equal(resolveHumanUatStatus({repository:'r',workPackageId:'w',entityType:'work_package',status:'PASS',items:pass,createdAt:'',updatedAt:'',source:''},pass),'PASS');
const override={repository:'r',workPackageId:'w',entityType:'work_package' as const,status:'PASS' as const,decision:'PASS' as const,decisionMode:'OWNER_OVERRIDE_PASS' as const,items:[{...pass[0],state:'PENDING' as const}],createdAt:'',updatedAt:'',source:''};
assert.equal(resolveHumanUatStatus(override,override.items),'PASS');
assert.equal(override.items[0].state,'PENDING');
assert.match(workspace,/lifecycleUatStatus/,'UAT workspace reads canonical lifecycle stage');
assert.match(workspace,/record\?\.status==='PASS'\|\|lifecycleUatStatus==='PASS'/,'closed canonical UAT PASS is preserved without a record');
assert.equal(workspace.includes('暂无可解析的 Owner Human UAT 计划。'),false,'missing checklist does not use long fallback prose');
assert.match(workspace,/currentStatus==='PASS'\?'已通过'/,'closed UAT renders completed state');
assert.match(workspace,/currentStatus==='NEEDS_REMEDIATION'\?'未通过'/,'failed UAT renders failed state');
assert.match(workspace,/enteredUat/,'not-entered copy is gated by lifecycle stage');
assert.match(workspace,/data-testid="uat-top-action-bar"/,'UAT business actions are in the top action bar');
assert.equal((workspace.match(/验收证据/g)??[]).length,1,'one evidence read action');
assert.equal((workspace.match(/运行结果/g)??[]).length,1,'one run result read action');
assert.equal((workspace.match(/原始指令/g)??[]).length,1,'one instruction read action');
assert.equal((workspace.match(/保存进度/g)??[]).length,1,'one save action');
assert.equal((workspace.match(/退回整改/g)??[]).length,1,'remediation uses the canonical label');
assert.equal((workspace.match(/通过UAT/g)??[]).length,1,'one UAT pass action');
for(const legacy of ['开始人工 UAT','继续人工 UAT','直接通过 UAT','标记需整改']) assert.equal(workspace.includes(legacy),false,`legacy UAT action removed: ${legacy}`);
assert.equal(workspace.includes('uat-round-actions'),false,'round navigation is not a second business action bar');
assert.equal(workspace.includes('class="uat-actions"'),false,'bottom business action bar removed');
assert.match(workspace,/uat-action-read/,'read actions share one row');
assert.match(workspace,/uat-action-mutate/,'mutation actions share one row');
for(const icon of ['📎','▶️','📄','💾','↩️','✅']) assert.equal(workspace.includes(icon),true,`action icon present: ${icon}`);
assert.equal(workspace.includes('负责人'),false,'owner summary card is removed');
assert.match(workspace,/type="checkbox"/,'checklist uses checkbox controls');
assert.match(workspace,/manualChecklist/,'missing checklist uses the manual compact checklist');
assert.match(workspace,/disabled={!editable}/,'closed checklist controls are read-only');
console.log('human UAT contract tests passed');
