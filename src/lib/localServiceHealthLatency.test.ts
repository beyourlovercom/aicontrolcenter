import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const root=new URL('../../',import.meta.url);
const server=readFileSync(new URL('vite.config.ts',root),'utf8');
const control=readFileSync(new URL('./controlService.ts',import.meta.url),'utf8');
const runtime=readFileSync(new URL('./runtimeManager.ts',import.meta.url),'utf8');
const bridge=readFileSync(new URL('./bridgeCore.ts',import.meta.url),'utf8');
const supervisor=readFileSync(new URL('../../scripts/aicc-run-supervisor.ts',import.meta.url),'utf8');

const liveRoute=server.match(/server\.middlewares\.use\('\/api\/live',[\s\S]*?\n  server\.middlewares\.use\('\/api\/health'/)?.[0]??'';
assert.match(liveRoute,/live:true/);
assert.doesNotMatch(liveRoute,/readLocalService|detectPortOwner|lsof|ps|git|codex/i);
const healthRoute=server.match(/server\.middlewares\.use\('\/api\/health',[\s\S]*?\n  server\.middlewares\.use\('\/api\/service\/status'/)?.[0]??'';
assert.match(healthRoute,/readLocalServiceHealthStatusAsync\(\)\.then/);
assert.doesNotMatch(healthRoute,/readLocalServiceHealthStatus\(\)/);
assert.doesNotMatch(healthRoute,/gh|git|codex|lsof|ps|detectPortOwner|readRuntime|readTask|readCodex/i);
const statusRoute=server.match(/server\.middlewares\.use\('\/api\/service\/status',[\s\S]*?\n  server\.middlewares\.use\('\/api\/service\/logs'/)?.[0]??'';
assert.match(statusRoute,/readLocalServiceStatusAsync\(\)\.then/);
assert.doesNotMatch(statusRoute,/readLocalServiceStatus\(|detectPortOwner/);
const healthStatus=control.slice(control.indexOf('export async function readLocalServiceStatusAsync'),control.indexOf('export function readLocalServiceSupervisorState'));
assert.match(healthStatus,/boundedHealthDiagnostic/);
assert.doesNotMatch(healthStatus,/execFileSync|execSync|spawnSync/);
assert.match(control,/HEALTH_CHILD_PROCESS_TIMEOUT_MS=500/);
const asyncPortOwner=control.slice(control.indexOf('export async function detectPortOwnerAsync'),control.indexOf('function repositoryAvailableForService'));
assert.equal((asyncPortOwner.match(/timeout:HEALTH_CHILD_PROCESS_TIMEOUT_MS/g)??[]).length,2);
assert.match(server,/readPullRequestsAsync\(\)\.then/);
assert.match(server,/readCiEvidenceAsync\(\)\.then/);
assert.match(server,/readCodexModelCapabilitiesAsync\(\),readCodexDefaultsAsync\(\)/);
assert.match(server,/readRuntimeHistoryAsync\(\)/);
assert.match(server,/readTaskProjectionReadOnly\(\)/);
const requestScope=server.slice(server.indexOf('function requestProjectScope'),server.indexOf('function scopedWpRecord'));
assert.match(requestScope,/getConfiguredProjectRegistry\(\)/,'read-only project query scope uses configured registry identity');
assert.doesNotMatch(requestScope,/getProject\(|getProjectRegistry\(|getActiveProject\(/,'read-only query scope must not trigger live Git validation');
assert.match(control,/export async function readCiEvidenceAsync/);
assert.match(control,/export async function refreshPrNavigationSnapshotAsync/);
const runtimeReadPath=runtime.slice(runtime.indexOf('async function readRuntimeFileCached'),runtime.indexOf('async function readRuntimeHistoryCached'));
assert.doesNotMatch(runtimeReadPath,/persistRuntimeTaskState/,'runtime read path must not write Task Registry');
const terminalOnData=supervisor.slice(supervisor.indexOf('child.onData'),supervisor.indexOf('child.onExit'));
assert.match(terminalOnData,/persist\(state,\{syncTask:false\}\)/,'PTY chunks persist runtime evidence without rewriting Task Registry');
assert.match(supervisor,/if\(options\.syncTask!==false\)persistRuntimeTaskState\(state\)/,'structured runtime persistence still syncs Task Registry');
const invalidation=runtime.slice(runtime.indexOf('export function invalidateRuntimeProjectionSnapshot'),runtime.indexOf('export function onRuntimeProjectionChange'));
assert.match(invalidation,/runtimeFileCache\.delete\(join\(STATE_DIR,name\)\)/,'single runtime changes invalidate only their cache entry');
assert.match(runtime,/invalidateRuntimeProjectionSnapshot\(name\)/,'runtime watcher forwards the changed filename');
assert.match(runtime,/invalidateRuntimeProjectionSnapshot\(target\)/,'local runtime writes invalidate only the written runtime file');
assert.match(runtime,/export async function readRuntimeHistoryAsync/);
assert.match(bridge,/export async function readTaskProjectionReadOnly/);
const activeTaskContext=bridge.slice(bridge.indexOf('export function activeTaskProjectContext'),bridge.indexOf('export function projectTaskModelForContext'));
assert.match(activeTaskContext,/getConfiguredProjectRegistry\(\)/,'Task projection reads configured project identity without live Git validation');
assert.doesNotMatch(activeTaskContext,/getProjectRegistry\(\)|getActiveProject\(\)/,'Task projection hot path must not execute validated Project Registry reads');
assert.match(bridge,/readTaskRunBranchEvidenceReadOnly/);

console.log('Local Service health latency invariants passed');
