import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createEmptyGlobalStateReadModel,entityIdentity,resolveExplicitBindings} from './globalStateReadModel.ts';
import {PR_IDENTITY_KEY,PR_LIFECYCLE_WORKSPACE_DUPLICATE_AUTHORITY,PR_NAVIGATION_SNAPSHOT_UI_AUTHORITY,prIdentityKey,projectPrLayer2} from './prCanonicalProjection.ts';

const scope={projectId:'aicc',repositoryIdentity:'org/repo',projectContextRevision:0};
const open={id:'local-row-a',repository:'org/repo',number:7,title:'Unrelated title',status:'IN_PROGRESS' as const,state:'OPEN' as const,sourceBranch:'feature/arbitrary',updatedAt:'2026-08-20T01:00:00.000Z'};
const mapped={...open,id:'local-row-b',repository:'org/repo',number:8,title:'Same title',workPackageId:'WP-EXPLICIT',state:'DRAFT' as const,updatedAt:'2026-08-20T01:01:00.000Z'};
const first=projectPrLayer2(createEmptyGlobalStateReadModel(scope),[open,mapped],'snapshot-1');
assert.equal(PR_IDENTITY_KEY,'REPOSITORY_PLUS_PR_NUMBER');
assert.equal(prIdentityKey(open.repository,open.number),'7');
assert.equal(first.records[0]?.presentationLifecycle,'OPEN');
assert.equal(first.records.find(item=>item.selectionId==='local-row-a')?.mappingStatus,'UNMAPPED');
assert.equal(resolveExplicitBindings(first.model,'WP_TO_PR',entityIdentity(scope,'WORK_PACKAGE','WP-EXPLICIT')).state,'BOUND','only persisted explicit WP binding projects');
assert.equal(first.records.find(item=>item.selectionId==='local-row-a')?.parentWpId,null,'title and branch do not infer a WP binding');
assert.equal(first.model.entities.find(entity=>entity.identity.id==='7')?.dimensions[0]?.projectedValue.state,'KNOWN');
const openValue=first.model.entities.find(entity=>entity.identity.id==='7')?.dimensions[0]?.projectedValue;
assert.equal(openValue?.state,'KNOWN');
if(openValue?.state==='KNOWN')assert.equal(openValue.value,'OPEN');
const unknown=projectPrLayer2(first.model,[{...open,state:undefined,updatedAt:'2026-08-20T01:02:00.000Z'}],'snapshot-2');
assert.equal(unknown.records[0]?.presentationLifecycle,'UNKNOWN','missing lifecycle is not guessed');
assert.equal(unknown.records[0]?.lifecycle.state,'UNKNOWN');
const changed=projectPrLayer2(first.model,[{...open,state:'MERGED',updatedAt:'2026-08-20T01:03:00.000Z'},mapped],'snapshot-3');
assert.equal(changed.model.globalProjectionRevision,2,'a PR fact change advances global revision');
assert.equal(changed.model.entities.find(entity=>entity.identity.id==='7')?.projectionRevision,2,'exact PR entity revision advances');
assert.equal(changed.model.entities.some(entity=>entity.identity.id==='8'),true,'same repository PR remains project-scoped');
assert.equal(projectPrLayer2(changed.model,[{...open,state:'MERGED',updatedAt:'2026-08-20T01:03:00.000Z'},mapped],'snapshot-3').model,changed.model,'no-op reprojection preserves revision');
assert.equal(PR_NAVIGATION_SNAPSHOT_UI_AUTHORITY,false);
assert.equal(PR_LIFECYCLE_WORKSPACE_DUPLICATE_AUTHORITY,false);
const app=readFileSync(new URL('../App.svelte',import.meta.url),'utf8');
const left=readFileSync(new URL('../components/PrNavigation.svelte',import.meta.url),'utf8');
const center=readFileSync(new URL('../components/GlobalPrWorkspace.svelte',import.meta.url),'utf8');
const context=readFileSync(new URL('./context/entityContext.ts',import.meta.url),'utf8');
assert.match(app,/PrNavigation records=\{prLayer2\?\.records\?\?\[\]\}/,'left consumes Layer 2 safely before project bind');
assert.match(app,/GlobalPrWorkspace records=\{prLayer2\.records\}/,'center consumes Layer 2');
assert.match(context,/prLayer2RecordForSelection/,'right context consumes Layer 2');
assert.match(left,/filterPrLayer2Records/,'left filtering is owned by Layer 2');
assert.doesNotMatch(left,/prNavigationSnapshot/);
assert.doesNotMatch(center,/PullRequestRecord/);
console.log('AICC Phase 3 PR canonical projection contract passed');
