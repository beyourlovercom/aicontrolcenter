import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {resolveOwnerStatusProjection} from './context/ownerStatusProjection.ts';
import {resolveOwnerWorkflowStages} from './context/ownerStatusProjection.ts';
const workflow=readFileSync(new URL('../components/WorkflowTimeline.svelte',import.meta.url),'utf8');
const roadmap=readFileSync(new URL('../components/RoadmapTree.svelte',import.meta.url),'utf8');

const app=readFileSync(new URL('../App.svelte',import.meta.url),'utf8');
const actions=readFileSync(new URL('../components/entity/OwnerActionZone.svelte',import.meta.url),'utf8');
const header=readFileSync(new URL('../components/entity/EntityHeader.svelte',import.meta.url),'utf8');
assert.match(actions,/item\.report\?\.runId===runtime\.runId/,'report matching is bound to the active run');
assert.match(actions,/运行已完成，报告已生成/,'completed run with report has truthful action');
assert.match(actions,/运行已完成，正在生成运行报告/,'missing report remains explicitly pending');
assert.match(actions,/ownerStatusCode==='WAITING_UAT'/,'waiting UAT action uses projected Owner state');
assert.match(actions,/closed=context\.lifecycle\.currentStage==='CLOSED'/,'owner action uses canonical closed stage');
assert.match(actions,/已完成，无需操作/,'closed WP has no-op current action');
assert.equal(actions.includes("label:'启动执行',detail:'准备就绪，可以开始执行'"),true,'non-closed start action remains supported');
assert.ok(actions.indexOf("label:'开始人工 UAT'")<actions.indexOf("label:'查看报告'"),'UAT is prioritized over report access');
assert.equal((actions.match(/class="action primary"/g)??[]).length,1,'one primary Owner action');
assert.match(app,/resolveOwnerStatusProjection\(context,bridgeOutbox\)/,'all owner status surfaces use the shared projection');
assert.match(app,/resolveOwnerWorkflowStages\(context,bridgeOutbox\)/,'workflow uses the shared owner projection');
assert.match(app,/feedback\.state!==\'IDLE\'/,'idle feedback does not duplicate the current action card');
assert.equal(app.includes('等待 Owner 操作'),false,'duplicate idle owner action copy removed');
assert.match(header,/statusOverride/,'entity header consumes owner status projection');
assert.match(workflow,/getStatusPresentationMeta\(stage\.status\)/,'workflow labels use status presentation metadata');
assert.match(roadmap,/StatusDot status=\{node\.status\}/,'roadmap status consumes projected node status');
const context={type:'work_package',status:'WAITING_UAT',statusLabel:'等待人工 UAT',formalization:'FORMAL_READY',runtime:{runId:'run-1',phase:'COMPLETED',exitCode:0},lifecycle:{stages:[{id:'IMPLEMENTATION',status:'COMPLETE'},{id:'HUMAN_UAT',status:'WAITING_UAT'}]}} as any;
const projected=resolveOwnerStatusProjection(context,[{state:'READY',report:{runId:'run-1'}}]);
assert.equal(projected.status,'WAITING_UAT');
assert.equal(projected.hasRealBlocker,false);
const blocked=resolveOwnerStatusProjection({...context,status:'BLOCKED',statusLabel:'阻塞',lifecycle:{stages:[{id:'IMPLEMENTATION',status:'BLOCKED'}]}} as any,[]);
assert.equal(blocked.status,'BLOCKED');
assert.equal(resolveOwnerWorkflowStages(context,[{state:'READY',report:{runId:'run-1'}}]).find(stage=>stage.id==='IMPLEMENTATION')?.status,'COMPLETE');
console.log('overview projection matrix passed');
