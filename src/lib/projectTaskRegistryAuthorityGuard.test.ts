import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
const read=(file:string)=>readFileSync(join(process.cwd(),file),'utf8');
const worker=read('web-adapter/chrome-extension-current/service-worker.js');
const workerPoll=worker.match(/async function pollResult[\s\S]*?(?=async function remoteClaudeStatus)/)?.[0]??'';
assert.match(workerPoll,/\/api\/tasks\/result\?/,'Chrome POLL_RESULT reads Project Task Registry API');
assert.doesNotMatch(workerPoll,/\/api\/gpt-bridge\/outbox/,'Chrome POLL_RESULT must not read Outbox results');
const adapter=read('src/lib/webBridgeAdapter.ts');
const adapterPoll=adapter.match(/async pollMatchingResult[\s\S]*?(?=\n}\n\nexport function reportForComposer)/)?.[0]??'';
assert.match(adapterPoll,/\/api\/tasks\/result\?/,'WebBridgeClient reads Project Task Registry API');
assert.doesNotMatch(adapterPoll,/\/api\/gpt-bridge\/outbox/,'WebBridgeClient must not read Outbox results');
const legacy=read('web-adapter/chatgpt-aicc-bridge.js');
const legacyPoll=legacy.match(/function poll\(\)[\s\S]*?(?=async function insert)/)?.[0]??'';
assert.match(legacyPoll,/\/api\/tasks\/result\?/,'legacy adapter cannot retain Outbox result authority');
assert.doesNotMatch(legacyPoll,/\/api\/gpt-bridge\/outbox/);
const taskProjection=read('src/lib/taskResultProjection.ts');
assert.match(taskProjection,/source:'PROJECT_TASK_REGISTRY'\|'NONE'/);
assert.doesNotMatch(taskProjection,/EXACT_RUN_RUNTIME|EXACT_RUN_OUTBOX/);
assert.doesNotMatch(taskProjection,/args\.runtime\?\.canonicalResult|item\.report\?\.canonicalResult/);
const phase5=read('src/lib/runtimeResultFeedbackControlLoopProjection.ts');
assert.doesNotMatch(phase5,/for\(const runtime of runtimes\)if\(runtime\.canonicalResult\)/,'Phase5 cannot implicitly import Runtime results');
const app=read('src/App.svelte');
assert.match(app,/phase5ResultsFromTasks\(taskRecords\)/);
assert.doesNotMatch(app,/phase5ResultForRuntime|selectedTaskRuntime\?\.canonicalResult/);
const workspace=read('src/components/entity/RuntimeWorkspace.svelte');
assert.match(workspace,/canonicalTaskResultForRun/);
assert.doesNotMatch(workspace,/exactResultForRun/);
const loop=read('src/lib/gptAutoControlLoop.ts');
const recordResult=loop.match(/export function recordExecutionResult[\s\S]*?(?=export type CanonicalControlLoopReadModel)/)?.[0]??'';
assert.match(recordResult,/readProjectTaskResult/);
assert.doesNotMatch(recordResult,/report\.canonicalResult/);
const model=read('src/lib/model/projectModel.ts');
assert.doesNotMatch(model,/raw\.runtime\?\.canonicalResult/);
assert.match(model,/taskCanonicalResultsForWorkPackage/);
const runtime=read('src/lib/runtimeManager.ts');
assert.doesNotMatch(runtime,/export (?:async )?function readCanonicalResult/);
assert.doesNotMatch(runtime,/export function updateCanonicalResultReturn/);
const bridge=read('src/lib/bridgeCore.ts');
assert.match(bridge,/buildRunReport[\s\S]*?readProjectTaskResult/);
const vite=read('vite.config.ts');
assert.match(vite,/server\.middlewares\.use\('\/api\/tasks\/result'/);
assert.match(vite,/readProjectTaskResult\(\{projectId,repositoryIdentity\},runId\)/);
console.log('Project Task Registry result authority guard passed');
